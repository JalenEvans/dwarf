// ==================================================================
// Test 7: mixed_module — function + interface + type alias
// ==================================================================

#[test]
fn test_e2e_mixed_module() {
    let record_decl = LirDecl::RecordDef {
        name: "Point".into(),
        fields: vec![
            LirField {
                name: "x".into(),
                type_: Type::Named("Int".into()),
            },
            LirField {
                name: "y".into(),
                type_: Type::Named("Int".into()),
            },
        ],
        is_pub: true,
        span: s(),
    };
    let func_decl = LirDecl::Function {
        name: "getOrigin".into(),
        params: vec![],
        return_type: None,
        body: null_lit(),
        effect: Effect::Pure,
        hint: TargetHint::None,
        is_pub: true,
        is_generator: false,
        span: s(),
    };
    let union_decl = LirDecl::UnionDef {
        name: "Option".into(),
        variants: vec![
            LirVariant {
                name: "Some".into(),
                arg: Some(Type::Named("Int".into())),
            },
            LirVariant {
                name: "None".into(),
                arg: None,
            },
        ],
        is_pub: true,
        span: s(),
    };
    let result = emit_program(vec![record_decl, func_decl, union_decl]);
    // Verify all three declarations appear in order
    assert!(result.starts_with("// Generated by Dwarf v0.1.0 -- edit source, not this file"));
    assert!(result.contains("export interface Point"));
    assert!(result.contains("export function getOrigin"));
    assert!(result.contains("export type Option"));
    // Verify Interface appears before function (order preserved)
    let pos_point = result.find("interface Point").unwrap();
    let pos_get_origin = result.find("function getOrigin").unwrap();
    let pos_option = result.find("type Option").unwrap();
    assert!(
        pos_point < pos_get_origin,
        "record should come before function"
    );
    assert!(
        pos_get_origin < pos_option,
        "function should come before union"
    );
}

