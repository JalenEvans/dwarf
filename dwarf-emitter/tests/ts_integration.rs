//! End-to-end integration tests for the TypeScript backend.
//!
//! Each test constructs a complete LIR program (one or more declarations),
//! emits it through [`TypeScriptBackend`], and verifies the TypeScript
//! output matches the expected form.

use dwarf_emitter::backend::EmitterBackend;
use dwarf_emitter::ts::backend::TypeScriptBackend;
use dwarf_lir::{
    Effect, LirArm, LirBinaryOp, LirDecl, LirExpr, LirField, LirLiteral, LirParam, LirPat, LirStmt,
    LirVariant, TargetHint,
};
use dwarf_syntax::hir::Type;
use dwarf_syntax::span::Span;

// ------------------------------------------------------------------
// Helpers
// ------------------------------------------------------------------

fn s() -> Span {
    Span::new(0, 0, 0)
}

fn no_hint() -> TargetHint {
    TargetHint::None
}

fn int_lit(v: i64) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Int(v),
        hint: no_hint(),
        span: s(),
    }
}

fn str_lit(v: &str) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Str(v.to_string()),
        hint: no_hint(),
        span: s(),
    }
}

fn null_lit() -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Null,
        hint: no_hint(),
        span: s(),
    }
}

fn var(name: &str) -> LirExpr {
    LirExpr::Variable {
        name: name.to_string(),
        hint: no_hint(),
        span: s(),
    }
}

fn param(name: &str, type_: Option<Type>) -> LirParam {
    LirParam {
        name: name.to_string(),
        type_,
    }
}

fn emit_program(decls: Vec<LirDecl>) -> String {
    let mut backend = TypeScriptBackend::new("0.1.0");
    backend.emit_module(&decls).unwrap()
}

