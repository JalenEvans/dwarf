// ==================================================================
// Test 16: assert.equal(a,b) → expect(a).toBe(b)  [RED PHASE]
// ==================================================================
//
// The emitter currently only matches flat Variable func names
// ("assert"/"assert_eq"), so assert.equal (which uses a Member
// expression for the func) falls through to regular call emission.
// This test asserts the *desired* output and will fail until the
// emitter is extended.

#[test]
fn test_assert_equal_emits_expect_to_be() {
    let decl = LirDecl::Function {
        name: "main".into(),
        params: vec![],
        return_type: None,
        body: LirExpr::Call {
            func: Box::new(LirExpr::Member {
                obj: Box::new(LirExpr::Variable {
                    name: "assert".into(),
                    hint: no_hint(),
                    span: s(),
                }),
                field: "equal".into(),
                hint: no_hint(),
                span: s(),
            }),
            args: vec![var("a"), var("b")],
            hint: no_hint(),
            span: s(),
        },
        effect: Effect::Pure,
        hint: TargetHint::None,
        is_pub: true,
        is_generator: false,
        span: s(),
    };
    let result = emit_program(vec![decl]);
    assert_eq!(
        result,
        "// Generated by Dwarf v0.1.0 -- edit source, not this file\n\nexport function main() { return expect(a).toBe(b); }"
    );
}

