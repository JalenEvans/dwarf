#[test]
fn test_java_mixed_module() {
    let record_decl = LirDecl::RecordDef {
        name: "Point".into(),
        fields: vec![
            LirField {
                name: "x".into(),
                type_: Type::Named("Int".into()),
            },
            LirField {
                name: "y".into(),
                type_: Type::Named("Int".into()),
            },
        ],
        is_pub: true,
        span: s(),
    };
    let func_decl = LirDecl::Function {
        name: "getOrigin".into(),
        params: vec![],
        return_type: None,
        body: null_lit(),
        effect: Effect::Pure,
        hint: TargetHint::None,
        is_pub: true,
        span: s(),
    };
    let union_decl = LirDecl::UnionDef {
        name: "Option".into(),
        variants: vec![
            LirVariant {
                name: "Some".into(),
                arg: Some(Type::Named("Int".into())),
            },
            LirVariant {
                name: "None".into(),
                arg: None,
            },
        ],
        is_pub: true,
        span: s(),
    };
    let result = emit_program(vec![record_decl, func_decl, union_decl]);
    // Verify header
    assert!(
        result.starts_with("// Generated by Dwarf"),
        "should start with Java header"
    );
    // Verify all three declarations appear in order
    assert!(result.contains("Point"), "should contain Point");
    assert!(
        result.contains("getOrigin") || result.contains("get_origin"),
        "should contain getOrigin function"
    );
    assert!(
        result.contains("Option") || result.contains("Union"),
        "should contain Option union type"
    );
}

