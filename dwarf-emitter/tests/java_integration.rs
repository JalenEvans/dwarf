//! Integration tests for the Java backend.
//!
//! Each test constructs a complete LIR program (one or more declarations),
//! emits it through [`JavaBackend`], and verifies the Java output matches
//! the expected form.
//!
//! All tests should **fail** during the RED phase because the JavaBackend
//! stub returns `UnsupportedFeature` for every method.

use dwarf_emitter::backend::EmitterBackend;
use dwarf_emitter::java::backend::JavaBackend;
use dwarf_lir::{
    Effect, LirArm, LirBinaryOp, LirDecl, LirExpr, LirField, LirLiteral, LirParam, LirPat, LirStmt,
    LirUnaryOp, LirVariant, TargetHint,
};
use dwarf_syntax::hir::Type;
use dwarf_syntax::span::Span;

// ------------------------------------------------------------------
// Helpers
// ------------------------------------------------------------------

fn s() -> Span {
    Span::new(0, 0, 0)
}

fn no_hint() -> TargetHint {
    TargetHint::None
}

fn int_lit(v: i64) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Int(v),
        hint: no_hint(),
        span: s(),
    }
}

fn float_lit(v: f64) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Float(v),
        hint: no_hint(),
        span: s(),
    }
}

fn str_lit(v: &str) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Str(v.to_string()),
        hint: no_hint(),
        span: s(),
    }
}

fn bool_lit(v: bool) -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Bool(v),
        hint: no_hint(),
        span: s(),
    }
}

fn null_lit() -> LirExpr {
    LirExpr::Literal {
        value: LirLiteral::Null,
        hint: no_hint(),
        span: s(),
    }
}

fn var(name: &str) -> LirExpr {
    LirExpr::Variable {
        name: name.to_string(),
        hint: no_hint(),
        span: s(),
    }
}

fn param(name: &str, type_: Option<Type>) -> LirParam {
    LirParam {
        name: name.to_string(),
        type_,
    }
}

fn emit_program(decls: Vec<LirDecl>) -> String {
    let mut backend = JavaBackend::default();
    backend.emit_module(&decls).unwrap()
}

